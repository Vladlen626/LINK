// Writes src/items.gen.js from data/items.json: the items the game knows, how they look, what picking one up does
// and how often a broken pot or crate drops it.
import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const items = JSON.parse(fs.readFileSync(new URL('data/items.json', root), 'utf8'));

const table = Object.fromEntries(items.map(({ id, name, shape, color, effect }) => [id, { name, shape, color, effect }]));
const drops = items.filter(item => item.drop > 0).map(item => ({ id: item.id, weight: item.drop }));

const text = `// Generated by tools/gen-items.mjs from data/items.json: do not edit by hand.
export const ITEMS = ${JSON.stringify(table, null, 2)};

export const DROPS = ${JSON.stringify(drops, null, 2)};
`;
fs.writeFileSync(new URL('src/items.gen.js', root), text);
console.log(`src/items.gen.js: ${items.length} items`);
